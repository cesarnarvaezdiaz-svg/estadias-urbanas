let currentLang = "es";

function translateNode(node, value) {
  if (!node || value == null) return;
  node.textContent = value;
}

function applyLanguage(lang) {
  currentLang = translations[lang] ? lang : "es";
  const t = translations[currentLang];

  document.documentElement.lang = currentLang;
  document.title = t.pageTitle;
  document.querySelector("meta[name='description']")?.setAttribute("content", t.pageDescription);
  document.querySelector("meta[property='og:title']")?.setAttribute("content", t.pageTitle);
  document.querySelector("meta[property='og:description']")?.setAttribute("content", t.pageDescription);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    translateNode(node, t[node.dataset.i18n]);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = t[node.dataset.i18nPlaceholder];
    if (value) node.setAttribute("placeholder", value);
  });

  try {
    localStorage.setItem("urban.language", currentLang);
  } catch {
    // noop
  }

  document.dispatchEvent(new CustomEvent("urban:language-applied", { detail: { language: currentLang, translations: t } }));
}

function detectLang() {
  const lang = navigator.language || "es";
  if (lang.startsWith("en")) return "en";
  if (lang.startsWith("pt")) return "pt";
  return "es";
}

window.UrbanI18n = {
  applyLanguage,
  getLang: () => currentLang,
  t: (key) => translations[currentLang]?.[key] || translations.es[key] || key,
  all: translations
};

document.addEventListener("DOMContentLoaded", () => {
  const selector = document.querySelector("#language-select");
  const saved = localStorage.getItem("urban.language");
  const lang = saved && translations[saved] ? saved : detectLang();

  if (selector) {
    selector.value = lang;
    selector.addEventListener("change", (event) => applyLanguage(event.target.value));
  }

  applyLanguage(lang);
  window.addEventListener("load", () => applyLanguage(currentLang), { once: true });
});
